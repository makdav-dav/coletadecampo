-- ================================================================
-- OS EMERGENCIAL — acionamento de equipe terceira fora do horário
-- comercial / fins de semana (ex.: queda de árvore obstruindo via).
-- Reaproveita GPS e fotos do app (fotos: entidade 'os_emergencial').
--
-- COMO RODAR:
--   Supabase → SQL Editor → New query → cole tudo → RUN.
--   Rode DEPOIS do acesso_rls.sql (usa as funções de papel).
--   Seguro rodar de novo (usa "if not exists" / recria policies).
-- ================================================================

create table if not exists public.os_emergencial (
  id_os         uuid primary key,
  descricao     text,              -- o que aconteceu (queda de árvore, etc.)
  endereco      text,
  lat double precision, lng double precision,
  risco_rede    boolean default false,   -- fio energizado envolvido (não atuar, acionar concessionária)
  status        text default 'aberta',  -- aberta | atendida | concluida
  numero_whatsapp text,            -- número acionado no momento da abertura
  obs_conclusao text,
  aberto_por    text,
  aberto_em     timestamptz default now(),
  atendido_em   timestamptz,
  concluido_em  timestamptz,
  criado_em     timestamptz default now(),
  criado_por    text
);

create index if not exists idx_os_emerg_criado on public.os_emergencial(criado_em desc);
create index if not exists idx_os_emerg_status on public.os_emergencial(status);

-- Campos do modelo de OS Emergencial (cabeçalho/ocorrência/atendimento/execução)
alter table public.os_emergencial add column if not exists quem_acionou text;         -- Defesa Civil, Guarda, Bombeiros, munícipe, 156...
alter table public.os_emergencial add column if not exists situacao jsonb;            -- ["Via totalmente obstruída", ...]
alter table public.os_emergencial add column if not exists risco_vitimas boolean;
alter table public.os_emergencial add column if not exists risco_transito boolean;
alter table public.os_emergencial add column if not exists equipe_responsavel text;   -- equipe/responsável que atendeu
alter table public.os_emergencial add column if not exists equipamentos text;         -- motosserra, caminhão, sinalização, EPIs...
alter table public.os_emergencial add column if not exists pendencias text;           -- ex.: remoção do tronco no dia útil, acionar concessionária

-- Numeração sequencial (100, 101, ...) gerada pelo banco: o app grava offline,
-- então o número só pode nascer no servidor para não repetir entre aparelhos.
-- As OS já existentes são numeradas pela ordem de criação.
do $$
begin
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'os_emergencial' and column_name = 'numero') then
    alter table public.os_emergencial add column numero integer;
    update public.os_emergencial o set numero = s.n
      from (select id_os, 99 + row_number() over (order by criado_em, id_os) as n from public.os_emergencial) s
      where s.id_os = o.id_os;
    alter table public.os_emergencial alter column numero set not null;
    alter table public.os_emergencial alter column numero add generated by default as identity;
    perform setval(pg_get_serial_sequence('public.os_emergencial', 'numero'),
                   coalesce((select max(numero) + 1 from public.os_emergencial), 100), false);
    alter table public.os_emergencial add constraint os_emergencial_numero_key unique (numero);
  end if;
end $$;

-- RLS: mesmas regras dos outros módulos
--   select: autorizado · insert: coletor+ ·
--   update/delete: editor/admin OU coletor no próprio registro
do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname='public' and tablename='os_emergencial' loop
    execute format('drop policy %I on public.os_emergencial', p.policyname);
  end loop;
  alter table public.os_emergencial enable row level security;
  create policy "autorizados leem" on public.os_emergencial for select to authenticated using (public.is_autorizado());
  create policy "coletores inserem" on public.os_emergencial for insert to authenticated with check (public.pode_coletar());
  create policy "edita tudo ou o proprio (upd)" on public.os_emergencial for update to authenticated using (public.pode_editar_tudo() or (public.pode_coletar() and criado_por = (auth.jwt() ->> 'email'))) with check (public.pode_editar_tudo() or (public.pode_coletar() and criado_por = (auth.jwt() ->> 'email')));
  create policy "edita tudo ou o proprio (del)" on public.os_emergencial for delete to authenticated using (public.pode_editar_tudo() or (public.pode_coletar() and criado_por = (auth.jwt() ->> 'email')));
end $$;
